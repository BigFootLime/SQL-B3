\echo '=== Exercice 1.7 - transaction annulee ==='
BEGIN;
INSERT INTO test_users (username, email)
VALUES ('dave', 'dave@example.com');
SELECT username, email FROM test_users WHERE username = 'dave';
ROLLBACK;
SELECT COUNT(*) AS dave_apres_rollback
FROM test_users
WHERE username = 'dave';

\echo '=== Exercice 1.7 - transaction validee ==='
BEGIN;
INSERT INTO test_users (username, email)
VALUES ('dave', 'dave@example.com');
COMMIT;
SELECT username, email FROM test_users WHERE username = 'dave';

\echo '=== Defi optionnel - table notes ==='
