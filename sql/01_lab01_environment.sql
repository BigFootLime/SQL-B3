    ('Installation', 'PostgreSQL fonctionne dans Docker.'),
    ('psql', 'Les meta-commandes commencent par un antislash.'),
    ('DDL', 'CREATE TABLE modifie la structure.'),
    ('DML', 'INSERT, UPDATE et DELETE modifient les donnees.'),
    ('Transaction', 'ROLLBACK annule et COMMIT valide.');

SELECT *
FROM notes
WHERE created_at::date = CURRENT_DATE
ORDER BY note_id;

UPDATE notes
SET title = 'Installation PostgreSQL'
WHERE note_id = 1
RETURNING *;

DELETE FROM notes RETURNING note_id;
