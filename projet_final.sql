CREATE OR REPLACE FUNCTION get_search_suggestions(p_partial_query TEXT,p_limit_count INTEGER DEFAULT 10)
RETURNS TABLE (suggestion TEXT,frequency INTEGER,similarity_score REAL)
LANGUAGE sql STABLE AS $$
    SELECT s.suggestion,s.frequency,similarity(s.suggestion,lower(p_partial_query))
    FROM search_suggestions s
    WHERE s.scope=search_scope() AND NULLIF(btrim(p_partial_query),'') IS NOT NULL
      AND (starts_with(s.suggestion,lower(p_partial_query)) OR similarity(s.suggestion,lower(p_partial_query))>=0.20)
    ORDER BY starts_with(s.suggestion,lower(p_partial_query)) DESC,
             s.frequency DESC,similarity(s.suggestion,lower(p_partial_query)) DESC,s.suggestion
    LIMIT LEAST(GREATEST(p_limit_count,1),50)
$$;

