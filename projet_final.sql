CREATE OR REPLACE FUNCTION calculate_user_reputation(p_user_id INTEGER)
RETURNS INTEGER
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    v_upvotes INTEGER;
    v_downvotes INTEGER;
    v_reponses_acceptees INTEGER;
    v_total INTEGER;
BEGIN
    SELECT
        COUNT(*) FILTER (WHERE v.vote_type_id = 2),
        COUNT(*) FILTER (WHERE v.vote_type_id = 3)
    INTO v_upvotes, v_downvotes
    FROM votes v
    JOIN posts p ON p.id = v.post_id
    WHERE p.owner_user_id = p_user_id;

    SELECT COUNT(*)
    INTO v_reponses_acceptees
    FROM posts reponse
    WHERE reponse.owner_user_id = p_user_id
      AND reponse.post_type_id = 2
      AND EXISTS (
          SELECT 1
          FROM posts question
          WHERE question.accepted_answer_id = reponse.id
      );

    v_total := COALESCE(v_upvotes, 0) * 10
             - COALESCE(v_downvotes, 0) * 2
             + COALESCE(v_reponses_acceptees, 0) * 15;
    RETURN GREATEST(v_total, 1);
END;
$$;

SELECT
