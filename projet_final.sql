CREATE OR REPLACE FUNCTION check_and_award_badges(p_user_id INTEGER)
RETURNS VOID
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_user_id IS NULL THEN
        RETURN;
    END IF;
    -- Une attribution à la fois par utilisateur ; pas de doublon concurrent.
    PERFORM pg_advisory_xact_lock(73412, p_user_id);

    IF EXISTS (
        SELECT 1
        FROM posts reponse
        WHERE reponse.owner_user_id = p_user_id
          AND reponse.post_type_id = 2
          AND EXISTS (
              SELECT 1 FROM posts question
              WHERE question.accepted_answer_id = reponse.id
          )
    ) AND NOT EXISTS (
        SELECT 1 FROM badges WHERE user_id = p_user_id AND name = 'Scholar'
    ) THEN
        INSERT INTO badges (user_id, name, class) VALUES (p_user_id, 'Scholar', 3);
    END IF;

    IF EXISTS (
        SELECT 1 FROM votes WHERE user_id = p_user_id AND vote_type_id = 2
    ) AND NOT EXISTS (
        SELECT 1 FROM badges WHERE user_id = p_user_id AND name = 'Supporter'
    ) THEN
        INSERT INTO badges (user_id, name, class) VALUES (p_user_id, 'Supporter', 3);
    END IF;

    IF EXISTS (
        SELECT 1 FROM votes WHERE user_id = p_user_id AND vote_type_id = 3
    ) AND NOT EXISTS (
        SELECT 1 FROM badges WHERE user_id = p_user_id AND name = 'Critic'
    ) THEN
        INSERT INTO badges (user_id, name, class) VALUES (p_user_id, 'Critic', 3);
    END IF;

    IF EXISTS (
        SELECT 1 FROM posts
        WHERE owner_user_id = p_user_id
          AND post_type_id = 2
          AND score >= 10
    ) AND NOT EXISTS (
        SELECT 1 FROM badges WHERE user_id = p_user_id AND name = 'Nice Answer'
    ) THEN
        INSERT INTO badges (user_id, name, class) VALUES (p_user_id, 'Nice Answer', 3);
    END IF;

    IF EXISTS (
        SELECT 1 FROM posts
        WHERE owner_user_id = p_user_id
          AND post_type_id = 1
          AND view_count >= 1000
    ) AND NOT EXISTS (
        SELECT 1 FROM badges WHERE user_id = p_user_id AND name = 'Popular Question'
    ) THEN
        INSERT INTO badges (user_id, name, class) VALUES (p_user_id, 'Popular Question', 3);
    END IF;
END;
$$;

CREATE OR REPLACE FUNCTION trigger_award_badges_from_vote()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_owner_id INTEGER;
BEGIN
    PERFORM check_and_award_badges(NEW.user_id);
    SELECT owner_user_id INTO v_owner_id FROM posts WHERE id = NEW.post_id;
    PERFORM check_and_award_badges(v_owner_id);
    RETURN NULL;
END;
$$;

CREATE TRIGGER trig_award_badges_vote
AFTER INSERT ON votes
FOR EACH ROW EXECUTE FUNCTION trigger_award_badges_from_vote();

