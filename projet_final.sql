CREATE OR REPLACE FUNCTION audit_posts()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO posts_audit (post_id, operation, new_data, changed_by)
        VALUES (NEW.id, TG_OP, to_jsonb(NEW), current_user);
    ELSIF TG_OP = 'UPDATE' THEN
        INSERT INTO posts_audit (post_id, operation, old_data, new_data, changed_by)
        VALUES (NEW.id, TG_OP, to_jsonb(OLD), to_jsonb(NEW), current_user);
    ELSE
        INSERT INTO posts_audit (post_id, operation, old_data, changed_by)
        VALUES (OLD.id, TG_OP, to_jsonb(OLD), current_user);
    END IF;
    RETURN NULL;
END;
$$;



CREATE OR REPLACE FUNCTION safe_divide(p_numerateur NUMERIC, p_denominateur NUMERIC)
RETURNS NUMERIC
LANGUAGE plpgsql
IMMUTABLE
AS $$
BEGIN
    IF p_denominateur = 0 THEN
        RETURN NULL;
    END IF;
    RETURN p_numerateur / p_denominateur;
END;
$$;

