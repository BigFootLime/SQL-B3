CREATE MATERIALIZED VIEW dashboard_posts AS
SELECT
    p.id AS post_id,
    p.title,
    p.score,
    u.display_name AS auteur,
    string_agg(DISTINCT t.tag_name, ', ' ORDER BY t.tag_name) AS tags,
    string_agg(DISTINCT te.description, ' | ' ORDER BY te.description) AS descriptions_tags,
    ps.page_views,
    ps.bounce_rate
FROM posts p
LEFT JOIN users u ON u.id = p.owner_user_id
LEFT JOIN post_tags pt ON pt.post_id = p.id
LEFT JOIN tags t ON t.id = pt.tag_id
LEFT JOIN tags_enriched_external te ON te.tag_name = t.tag_name
