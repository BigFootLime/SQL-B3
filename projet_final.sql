CREATE OR REPLACE FUNCTION get_question_thread(p_question_id INTEGER)
RETURNS TABLE (
    post_id INTEGER,
    post_type TEXT,
    author VARCHAR,
    content TEXT,
    score INTEGER,
    created_at TIMESTAMP
)
LANGUAGE plpgsql
STABLE
AS $$
BEGIN
    RETURN QUERY
    SELECT
        p.id,
        CASE p.post_type_id WHEN 1 THEN 'Question' ELSE 'Answer' END::TEXT,
        u.display_name,
        p.body,
        p.score,
        p.creation_date
    FROM posts p
    LEFT JOIN users u ON u.id = p.owner_user_id
    WHERE (p.id = p_question_id AND p.post_type_id = 1)
       OR (p.parent_id = p_question_id AND p.post_type_id = 2)
    ORDER BY CASE WHEN p.id = p_question_id THEN 0 ELSE 1 END,
             p.creation_date,
             p.id;
END;
$$;

