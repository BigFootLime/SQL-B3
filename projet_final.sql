CREATE OR REPLACE FUNCTION advanced_search(p_query_text TEXT,
    p_filters JSONB DEFAULT '{}', p_page INTEGER DEFAULT 1, p_page_size INTEGER DEFAULT 20)
RETURNS TABLE (post_id INTEGER, title VARCHAR, snippet TEXT, relevance REAL,
              post_score INTEGER, view_count INTEGER, answer_count INTEGER)
LANGUAGE plpgsql AS $$
DECLARE started timestamptz := clock_timestamp(); h TEXT; results JSONB;
        cached BOOLEAN := false; f JSONB := COALESCE(p_filters,'{}');
BEGIN
    IF p_query_text IS NULL OR btrim(p_query_text)='' OR length(p_query_text)>500 THEN
        RAISE EXCEPTION 'Recherche attendue : 1 a 500 caracteres' USING ERRCODE='22023';
    END IF;
    IF p_page IS NULL OR p_page < 1 OR p_page_size IS NULL OR p_page_size NOT BETWEEN 1 AND 100 THEN
        RAISE EXCEPTION 'Page >= 1 et taille de page entre 1 et 100' USING ERRCODE='22023';
    END IF;
    PERFORM validate_search_filters(f);
    h := encode(digest(jsonb_build_array(search_scope(),lower(btrim(p_query_text)),
                                       f,p_page,p_page_size)::text,'sha256'),'hex');
    SELECT c.results INTO results FROM search_cache c
    WHERE c.query_hash=h AND c.scope=search_scope()
      AND c.created_at > clock_timestamp()-INTERVAL '5 minutes';
    IF FOUND THEN
        cached := true;
        UPDATE search_cache c SET hits=c.hits+1 WHERE c.query_hash=h;
    ELSE
        SELECT COALESCE(jsonb_agg(to_jsonb(r) ORDER BY r.ord),'[]') INTO results
        FROM (
            SELECT s.*, row_number() OVER (
                ORDER BY (s.match_type='exact') DESC,s.relevance DESC,s.post_id) AS ord
            FROM ranked_search(p_query_text,f) s
            ORDER BY (s.match_type='exact') DESC,s.relevance DESC,s.post_id
            LIMIT p_page_size OFFSET (p_page::bigint-1)*p_page_size
        ) r;
        INSERT INTO search_cache (query_hash,query_text,filters,page,page_size,results,scope)
        VALUES (h,p_query_text,f,p_page,p_page_size,results,search_scope())
        ON CONFLICT (query_hash) DO UPDATE
        SET results=EXCLUDED.results, created_at=clock_timestamp(), hits=search_cache.hits+1;
    END IF;
    INSERT INTO search_suggestions (suggestion,scope)
    VALUES (lower(btrim(p_query_text)),search_scope())
    ON CONFLICT (scope,suggestion) DO UPDATE
    SET frequency=search_suggestions.frequency+1,last_used=clock_timestamp();
    INSERT INTO search_log (query_text,filters,result_count,cache_hit,duration_ms,scope)
    VALUES (p_query_text,f,jsonb_array_length(results),cached,
            extract(epoch FROM (clock_timestamp()-started))*1000,search_scope());
    RETURN QUERY SELECT x.post_id,x.title,x.snippet,x.relevance,x.post_score,x.view_count,x.answer_count
    FROM jsonb_to_recordset(results) AS x(post_id integer,title varchar,snippet text,
         relevance real,post_score integer,view_count integer,answer_count integer,ord bigint)
    ORDER BY x.ord;
END $$;

