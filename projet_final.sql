-- Une erreur de type est signalée : un filtre mal formé ne doit pas être ignoré.
CREATE FUNCTION validate_search_filters(f JSONB) RETURNS void
LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE k TEXT; n NUMERIC;
BEGIN
    IF jsonb_typeof(f) IS DISTINCT FROM 'object' THEN
        RAISE EXCEPTION 'Les filtres doivent former un objet JSON' USING ERRCODE='22023';
    END IF;
    FOR k IN SELECT jsonb_object_keys(f) LOOP
        IF k NOT IN ('tags','min_score','has_accepted_answer','date_range',
                     'date_from','date_to','language','metadata') THEN
            RAISE EXCEPTION 'Filtre inconnu : %', k USING ERRCODE='22023';
        END IF;
    END LOOP;
    IF f ? 'tags' THEN
        IF jsonb_typeof(f->'tags') IS DISTINCT FROM 'array' THEN
            RAISE EXCEPTION 'tags doit etre un tableau' USING ERRCODE='22023';
        END IF;
        IF EXISTS (SELECT FROM jsonb_array_elements(f->'tags') x
                   WHERE jsonb_typeof(x) <> 'string') THEN
            RAISE EXCEPTION 'Chaque tag doit etre une chaine' USING ERRCODE='22023';
        END IF;
    END IF;
    IF f ? 'min_score' THEN
        IF jsonb_typeof(f->'min_score') IS DISTINCT FROM 'number' THEN
            RAISE EXCEPTION 'min_score doit etre un entier' USING ERRCODE='22023';
        END IF;
        n := (f->>'min_score')::numeric;
        IF n <> trunc(n) OR n NOT BETWEEN -2147483648 AND 2147483647 THEN
            RAISE EXCEPTION 'min_score hors limites' USING ERRCODE='22023';
        END IF;
    END IF;
    IF f ? 'has_accepted_answer' AND
       jsonb_typeof(f->'has_accepted_answer') IS DISTINCT FROM 'boolean' THEN
        RAISE EXCEPTION 'has_accepted_answer doit etre un booleen' USING ERRCODE='22023';
    END IF;
    IF f ? 'metadata' AND jsonb_typeof(f->'metadata') IS DISTINCT FROM 'object' THEN
        RAISE EXCEPTION 'metadata doit etre un objet' USING ERRCODE='22023';
    END IF;
    IF f ? 'language' AND jsonb_typeof(f->'language') IS DISTINCT FROM 'string' THEN
        RAISE EXCEPTION 'language doit etre une chaine' USING ERRCODE='22023';
    END IF;
    IF f ? 'date_range' AND jsonb_typeof(f->'date_range') IS DISTINCT FROM 'object' THEN
        RAISE EXCEPTION 'date_range doit etre un objet' USING ERRCODE='22023';
    END IF;
    IF f ? 'date_range' AND EXISTS (
        SELECT FROM jsonb_object_keys(f->'date_range') key WHERE key NOT IN ('from','to')
    ) THEN
        RAISE EXCEPTION 'date_range accepte from et to' USING ERRCODE='22023';
    END IF;
    IF COALESCE(f->>'date_from', f#>>'{date_range,from}')::timestamp >
       COALESCE(f->>'date_to', f#>>'{date_range,to}')::timestamp THEN
        RAISE EXCEPTION 'La date de debut depasse la date de fin' USING ERRCODE='22023';
    END IF;
END $$;

CREATE OR REPLACE FUNCTION faceted_search(p_filters JSONB)
RETURNS TABLE (post_id INTEGER, title VARCHAR, score INTEGER, tags VARCHAR)
LANGUAGE plpgsql STABLE AS $$
DECLARE f JSONB := COALESCE(p_filters, '{}'::jsonb);
BEGIN
    PERFORM validate_search_filters(f);
    RETURN QUERY SELECT p.id, p.title, p.score, p.tags FROM posts p
    WHERE p.post_type_id = 1
      AND p.score >= COALESCE((f->>'min_score')::integer, -2147483648)
      AND p.creation_date >= COALESCE(
          COALESCE(f->>'date_from',f#>>'{date_range,from}')::timestamp, '-infinity')
      AND p.creation_date < COALESCE(
          COALESCE(f->>'date_to',f#>>'{date_range,to}')::date + INTERVAL '1 day', 'infinity')
      AND (NOT f ? 'has_accepted_answer' OR
           (p.accepted_answer_id IS NOT NULL) = (f->>'has_accepted_answer')::boolean)
      AND (NOT f ? 'metadata' OR p.metadata @> (f->'metadata'))
      AND NOT EXISTS (
          SELECT FROM jsonb_array_elements_text(f->'tags') wanted(tag)
          WHERE NOT EXISTS (SELECT FROM post_tags pt JOIN tags t ON t.id = pt.tag_id
                            WHERE pt.post_id = p.id AND t.tag_name = wanted.tag))
    ORDER BY p.score DESC, p.id;
END $$;

-- RLS reste active : cette fonction s'exécute avec les droits de l'appelant.
CREATE FUNCTION ranked_search(q TEXT, f JSONB DEFAULT '{}')
RETURNS TABLE (post_id INTEGER, title VARCHAR, snippet TEXT, relevance REAL,
              post_score INTEGER, view_count INTEGER, answer_count INTEGER, match_type TEXT)
LANGUAGE sql STABLE
SET pg_trgm.word_similarity_threshold = '0.35'
AS $$
    WITH config AS (
        SELECT search_config_for(COALESCE(f->>'language',
               current_setting('app.search_language', true))) AS cfg
    ), queries AS (
        SELECT cfg, websearch_to_tsquery(cfg, q) AS local_query,
               websearch_to_tsquery('english', q) AS english_query FROM config
    ), exacts AS MATERIALIZED (
        SELECT p.*, CASE WHEN p.search_config = r.cfg THEN r.local_query
                        ELSE r.english_query END AS query,
               'exact'::text AS match_type
        FROM posts p CROSS JOIN queries r
        JOIN faceted_search(f) allowed ON true
        WHERE allowed.post_id = p.id AND (
            (p.search_config = r.cfg AND p.search_vector @@ r.local_query) OR
            (p.search_config = 'english'::regconfig AND p.search_vector @@ r.english_query))
    ), fuzzy AS (
        SELECT p.*, r.english_query AS query, 'fuzzy'::text AS match_type
        FROM posts p CROSS JOIN queries r
        JOIN faceted_search(f) allowed ON true
        WHERE allowed.post_id = p.id AND (SELECT COUNT(*) FROM exacts) < 5
          AND (p.title % q OR q <% p.title)
          AND NOT EXISTS (SELECT FROM exacts e WHERE e.id = p.id)
    ), candidates AS (SELECT * FROM exacts UNION ALL SELECT * FROM fuzzy)
    SELECT p.id, p.title,
           ts_headline(p.search_config,
               regexp_replace(COALESCE(p.body,''), '<[^>]+>', ' ', 'g'), p.query,
               'MaxWords=35, MinWords=15, StartSel=<b>, StopSel=</b>'),
           (CASE WHEN p.match_type = 'exact' THEN
                1.0 + ts_rank_cd(p.search_vector,p.query)
            ELSE 0.5 * word_similarity(q, COALESCE(p.title,'')) END
            + 0.15 * ln(GREATEST(p.score,0)+1)
            + 0.10 * ln(GREATEST(p.view_count,0)+1)
            + 0.10 / (1 + GREATEST(extract(epoch FROM (CURRENT_TIMESTAMP-p.creation_date))
                                   / 31557600.0,0)))::real,
           p.score, p.view_count, p.answer_count, p.match_type
    FROM candidates p
    ORDER BY (p.match_type = 'exact') DESC, 4 DESC, p.id
$$;

